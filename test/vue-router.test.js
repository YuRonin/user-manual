'use strict';

/*
 * Vue Router 适配器 + Vue SFC 依赖（docs/MULTI_FRAMEWORK_PLAN.md 阶段 3）：
 * 路由记录去向（redirect 布局、跨文件展开、兜底）、同一组件按 props 区分的多个页面、
 * .vue 的 script / style / 模板自动导入组件进入依赖图，components.d.ts 缺失时保守降级。
 */

const assert = require('assert');
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const fx = require('./fixtures');

const CLI = path.resolve(__dirname, '..', 'bin', 'manual.js');

let passed = 0;
const failures = [];
function test(name, fn) {
  try { fn(); passed++; process.stdout.write(`  ✓ ${name}\n`); }
  catch (error) { failures.push({ name, error }); process.stdout.write(`  ✗ ${name}\n    ${error.stack || error}\n`); }
}

function run(root, cmd, args = []) {
  return spawnSync(process.execPath, [CLI, cmd, '--project-root', root, ...args], { encoding: 'utf8' });
}

function inspectJson(root) {
  const r = run(root, 'inspect', ['--json']);
  assert.strictEqual(r.status, 0, `inspect 失败: ${r.stderr}${r.stdout}`);
  return JSON.parse(r.stdout);
}

function withProject(make, fn) {
  const root = make();
  try {
    const init = run(root, 'init', ['--base-url', 'http://localhost:5173']);
    assert.strictEqual(init.status, 0, init.stderr);
    fn(root);
  } finally {
    fx.cleanup(root);
  }
}

function pageOf(root, out, route) {
  const id = out.pages.find((p) => p.route === route)?.id;
  assert.ok(id, `没有页面 ${route}`);
  return yaml.load(fs.readFileSync(path.join(root, '.manual/pages', `${id}.yaml`), 'utf8'));
}

const ROUTER = `import { createRouter, createWebHistory } from 'vue-router'
import HomeView from '@/views/HomeView.vue'
import LoginView from '@/views/Login/LoginView.vue'
import specialRoutes from './special'
import { useStore } from '@/stores/main'

const router = createRouter({
  history: createWebHistory(import.meta.env.BASE_URL),
  routes: [
    {
      path: '/',
      name: 'home',
      component: HomeView,
      redirect: '/list',
      children: [
        // 列表
        { path: 'list', name: 'List', component: () => import('@/views/List.vue') },
        {
          path: 'list/item/:itemId',
          component: () => import('@/views/List.vue'),
          props: { mode: 'page' },
        },
        ...specialRoutes,
      ],
    },
    { path: '/login', name: 'login', component: LoginView },
    { path: '/detail/:id', component: () => import('../views/Detail.vue') },
    { path: '/:pathMatch(.*)*', redirect: '/list' },
  ],
})

router.beforeEach(() => { useStore() })
export default router
`;

const SPECIAL = `import type { RouteRecordRaw } from 'vue-router'
const routes: RouteRecordRaw[] = [
  { path: 'special', component: () => import('@/views/Special/index.vue') },
  { path: 'special/writing', component: () => import('@/views/Special/CourseList.vue'), props: { module: 'writing' } },
  { path: 'special/grammar', component: () => import('@/views/Special/CourseList.vue'), props: { module: 'grammar' } },
]
export default routes
`;

const COMPONENTS_DTS = `/* eslint-disable */
// Generated by unplugin-vue-components
export {}
declare module 'vue' {
  export interface GlobalComponents {
    AButton: typeof import('ant-design-vue/es')['Button']
    NeoTag: typeof import('./src/components/NeoTag.vue')['default']
  }
}
`;

const SFC = (body) => `<template>\n  <div>${body}</div>\n</template>\n<script setup lang="ts">\n</script>\n`;

function vueFixture({ dts = true } = {}) {
  const root = fx.makeTempDir('manual-vue-');
  fx.writeFile(root, 'package.json', JSON.stringify({
    dependencies: { vue: '^3.5.13', 'vue-router': '^4.5.0', 'ant-design-vue': '^4.2.6' },
    devDependencies: { vite: '^6.1.0', 'unplugin-vue-components': '^28.8.0' },
  }));
  // 与 create-vue 一致：根 tsconfig 只有 references，别名写在 tsconfig.app.json
  fx.writeFile(root, 'tsconfig.json', JSON.stringify({ files: [], references: [{ path: './tsconfig.app.json' }] }));
  fx.writeFile(root, 'tsconfig.app.json', JSON.stringify({ include: ['src/**/*'], compilerOptions: { paths: { '@/*': ['./src/*'] } } }));
  fx.writeFile(root, 'vite.config.ts', 'export default {}\n');
  if (dts) fx.writeFile(root, 'components.d.ts', COMPONENTS_DTS);
  fx.writeFile(root, 'src/main.ts', "import router from './router'\nexport default router\n");
  fx.writeFile(root, 'src/router/index.ts', ROUTER);
  fx.writeFile(root, 'src/router/special.ts', SPECIAL);
  fx.writeFile(root, 'src/stores/main.ts', 'export function useStore() { return {} }\n');
  fx.writeFile(root, 'src/views/HomeView.vue', '<template><SideMenu /><router-view /></template>\n<script setup>\nimport SideMenu from \'./SideMenu.vue\'\n</script>\n');
  fx.writeFile(root, 'src/views/SideMenu.vue', SFC('菜单'));
  fx.writeFile(root, 'src/views/Login/LoginView.vue', SFC('登录'));
  // 页面：script setup 导入的组件、模板里自动导入的本地组件（NeoTag）与第三方组件（a-button）、style 里的 @import、导入 router
  fx.writeFile(root, 'src/views/List.vue', `<template>
  <Card />
  <neo-tag />
  <a-button>新建</a-button>
</template>
<script setup lang="ts">
import Card from '@/components/Card.vue'
import router from '@/router'
const go = () => router.push('/')
</script>
<style lang="less" scoped>
@import '@/assets/list.less';
</style>
`);
  fx.writeFile(root, 'src/views/Detail.vue', SFC('详情'));
  fx.writeFile(root, 'src/views/Special/index.vue', SFC('专项'));
  fx.writeFile(root, 'src/views/Special/CourseList.vue', SFC('课程'));
  fx.writeFile(root, 'src/components/Card.vue', SFC('卡片'));
  fx.writeFile(root, 'src/components/NeoTag.vue', SFC('标签'));
  fx.writeFile(root, 'src/assets/list.less', '.list { color: red; }\n');
  return root;
}

process.stdout.write('\nvue router\n');

test('逐条核对路由记录：redirect 父路由是布局、跨文件展开、兜底路由、动态参数', () => {
  withProject(vueFixture, (root) => {
    const out = inspectJson(root);
    assert.strictEqual(out.discovery.adapter, 'vue-router-objects');
    assert.strictEqual(out.discovery.completeness, 'complete', JSON.stringify(out.discovery));
    assert.deepStrictEqual(out.discovery.counts, { routeRecords: 9, pageRecords: 7, pages: 7, skipped: 2, unresolved: 0, conflicts: 0 });
    assert.deepStrictEqual(Object.fromEntries(out.pages.map((p) => [p.route, p.entry])), {
      '/detail/:id': 'src/views/Detail.vue',
      '/list': 'src/views/List.vue',
      '/list/item/:itemId': 'src/views/List.vue',
      '/login': 'src/views/Login/LoginView.vue',
      '/special': 'src/views/Special/index.vue',
      '/special/grammar': 'src/views/Special/CourseList.vue',
      '/special/writing': 'src/views/Special/CourseList.vue',
    });
    assert.deepStrictEqual(out.skipped.map((s) => s.reason).sort(), ['catch-all', 'layout-only']);
    const list = pageOf(root, out, '/list');
    assert.deepStrictEqual(list.dependencies.scope, ['src/views/HomeView.vue'], '父路由组件是布局依赖');
    assert.strictEqual(list.status.router, 'vue-router');
  });
});

test('.vue 依赖：script 导入、模板自动导入的本地组件、style @import 进依赖图；路由表与第三方组件不进', () => {
  withProject(vueFixture, (root) => {
    const out = inspectJson(root);
    const list = pageOf(root, out, '/list');
    assert.deepStrictEqual(list.dependencies.files, ['src/components/Card.vue', 'src/components/NeoTag.vue', 'src/views/HomeView.vue', 'src/views/SideMenu.vue']);
    assert.deepStrictEqual(list.dependencies.assets, ['src/assets/list.less']);
    assert.strictEqual(list.dependencies.completeness, 'complete', JSON.stringify(list.dependencies.unresolved));
    assert.match(list.analysis.parserVersion, /vue-sfc-1/);
    assert.match(list.analysis.parserVersion, /vr-objects-1/);
  });
});

test('同一组件按 props 区分的多个页面：各自独立；只改一条路由的 props 只影响那一个页面', () => {
  withProject(vueFixture, (root) => {
    let out = inspectJson(root);
    const ids = out.pages.filter((p) => p.entry === 'src/views/Special/CourseList.vue').map((p) => p.id);
    assert.strictEqual(new Set(ids).size, 2);
    const file = path.join(root, 'src/router/special.ts');
    fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace("props: { module: 'grammar' }", "props: { module: 'grammar', beta: true }"));
    out = inspectJson(root);
    const changed = out.impact.pages.filter((p) => p.status !== 'unchanged');
    assert.deepStrictEqual(changed.map((p) => p.id), [out.pages.find((p) => p.route === '/special/grammar').id]);
    assert.ok(changed[0].reasons.some((r) => r.startsWith('route-record-changed:')));
    assert.deepStrictEqual(out.renamed, []);
  });
});

test('改共用组件影响所有用到它的页面；改自动导入的组件能找到使用它的页面', () => {
  withProject(vueFixture, (root) => {
    inspectJson(root);
    fs.writeFileSync(path.join(root, 'src/views/Special/CourseList.vue'), SFC('课程列表（改）'));
    let out = inspectJson(root);
    let changed = out.impact.pages.filter((p) => p.status === 'changed').map((p) => out.pages.find((x) => x.id === p.id).route).sort();
    assert.deepStrictEqual(changed, ['/special/grammar', '/special/writing']);
    fs.writeFileSync(path.join(root, 'src/components/NeoTag.vue'), SFC('标签（改）'));
    out = inspectJson(root);
    changed = out.impact.pages.filter((p) => p.status === 'changed').map((p) => out.pages.find((x) => x.id === p.id).route).sort();
    assert.deepStrictEqual(changed, ['/list', '/list/item/:itemId']);
  });
});

test('找不到 components.d.ts：模板里来源不明的组件记为未解析，页面依赖覆盖降为 partial', () => {
  withProject(() => vueFixture({ dts: false }), (root) => {
    const out = inspectJson(root);
    const list = pageOf(root, out, '/list');
    assert.strictEqual(list.dependencies.completeness, 'partial');
    assert.ok(list.dependencies.unresolved.some((u) => /components\.d\.ts/.test(u) && /neo-tag/.test(u)), JSON.stringify(list.dependencies.unresolved));
    assert.ok(!list.dependencies.files.includes('src/components/NeoTag.vue'));
  });
});

test('router.addRoute() 运行时补充路由：记为未解析，完整性为 partial', () => {
  withProject(vueFixture, (root) => {
    const file = path.join(root, 'src/router/index.ts');
    fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace('export default router', "router.addRoute({ path: '/dyn', component: () => import('@/views/Detail.vue') })\nexport default router"));
    const out = inspectJson(root);
    assert.strictEqual(out.discovery.completeness, 'partial');
    assert.strictEqual(out.discovery.unresolved[0].reason, 'runtime-routes');
  });
});

